func lifecycleScenario(s string) bool {
	if parallelScenario(s) {
		return true
	}
	switch s {
	case "safe-safe-committed", "ambiguous-old", "ambiguous-new", "rotation-no-store", "rotation-no-proof", "rotation-committed", "cleanup-incomplete", "cleanup-complete":
		return true
	}
	return false
}

type lifecycleClassifier struct{}

func (lifecycleClassifier) Classify(e authowner.RPCError) authowner.Disposition {
	if e.Code == 1001 {
		return authowner.Safe
	}
	return authowner.Unknown
}

type lifecycleClock struct {
	mu    sync.Mutex
	value time.Time
}

func (c *lifecycleClock) now() time.Time { c.mu.Lock(); defer c.mu.Unlock(); return c.value }
func (c *lifecycleClock) set(v time.Time) {
	c.mu.Lock()
	defer c.mu.Unlock()
	if !v.Before(c.value) {
		c.value = v
	}
}

// The writer's entire executable behavior is closed here: no subprocess, network,
// selectable path or account input. Only generated bytes arrive through FD6.
func writerMain(args []string) int {
	if len(args) != 2 || os.Args[0] != "/proc/self/fd/4" {
		return 125
	}
	f := os.NewFile(5, "writer-context")
	defer f.Close()
	st, e := f.Stat()
	if e != nil || st.Mode()&os.ModeNamedPipe == 0 {
		return 125
	}
	b, e := io.ReadAll(io.LimitReader(f, 4097))
	var c ownerContext
	if e != nil || len(b) > 4096 || qualificationHash(b) != args[1] || wire.Decode(b, &c) != nil || !filepath.IsAbs(c.Root) || filepath.Clean(c.Root) != c.Root || c.Parent != os.Getppid() || c.Epoch != 1 {
		return 125
	}
	image := os.NewFile(4, "writer-image")
	defer image.Close()
	if _, e = image.Seek(0, io.SeekStart); e != nil {
		return 125
	}
	digest, e := descriptorDigest(image)
	if e != nil || digest != c.Image {
		return 125
	}
	data := os.NewFile(6, "writer-generated-data")
	defer data.Close()
	st, e = data.Stat()
	if e != nil || st.Mode()&os.ModeNamedPipe == 0 {
		return 125
	}
	native, e := io.ReadAll(io.LimitReader(data, 4097))
	if e != nil || len(native) > 4096 || qualificationHash(native) != c.Candidate {
		return 125
	}
	if unix.SetNonblock(7, true) != nil || unix.SetNonblock(8, true) != nil {
		return 125
	}
	ch := &ownerChannel{r: os.NewFile(8, "writer-input"), w: os.NewFile(7, "writer-output"), limit: 512}
	defer ch.r.Close()
	defer ch.w.Close()
	for _, pipe := range []*os.File{ch.r, ch.w} {
		st, e = pipe.Stat()
		if e != nil || st.Mode()&os.ModeNamedPipe == 0 || pipe.SetDeadline(time.Now().Add(25*time.Second)) != nil {
			return 125
		}
	}
	if egress.EnterWriterRole(args[1]) != nil {
		return 125
	}
	return writerCompose(c, ch, native)
}
func writerCompose(c ownerContext, ch *ownerChannel, native []byte) int {
	if ch.send("startup", nil, nil) != nil {
		return 1
	}
	persisted := false
	limit := 4
	if c.Member != "" {
		limit = 6
	} // Additional fresh challenges for the retained live singleton.
	for i := 0; i < limit; i++ {
		m, e := ch.read()
		if e != nil {
			return 1
		}
		switch m.Op {
		case "challenge":
			var nonce string
			if wire.Decode(m.Data, &nonce) != nil || len(nonce) != 64 || ch.send(m.Op, qualificationHash([]byte(c.Scenario+nonce)), nil) != nil {
				return 1
			}
		case "persist":
			if persisted || len(m.Data) != 0 && string(m.Data) != "null" {
				return 1
			}
			persisted = true
			if writerPersist(c.Root, native) != nil || ch.send(m.Op, nil, nil) != nil {
				return 1
			}
		default:
			return 1
		}
	}
	return 1
}
func writerPersist(root string, native []byte) error {
	home := filepath.Join(root, "home")
	tmp := filepath.Join(home, "native.pending")
	f, e := os.OpenFile(tmp, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if e != nil {
		return e
	}
	_, e = f.Write(native)
	if e == nil {
		e = f.Sync()
	}
	e = errors.Join(e, f.Close())
	if e != nil {
		return e
	}
	if e = os.Rename(tmp, filepath.Join(home, "auth.json")); e != nil {
		return e
	}
	d, e := os.Open(home)
	if e != nil {
		return e
	}
	return errors.Join(d.Sync(), d.Close())
}

type writerFact struct {
	Origin              ownerEpochFact
	Attempt             string
	Start               uint64
	Persisted, Survived bool
	Stop                egress.TerminationFacts
}
type lifecycleWriter struct {
	session      *ownerSession
	fact         writerFact
	root, digest string
}

func startWriter(ctx context.Context, c ownerContext, broker *os.File, attempt string, native []byte) (*lifecycleWriter, error) {
	r, w, e := os.Pipe()
	if e != nil {
		return nil, e
	}
	defer r.Close()
	defer w.Close()
	if _, e = w.Write(native); e != nil {
		return nil, e
	}
	w.Close()
	c.Scenario = attempt
	c.Candidate = qualificationHash(native)
	c.Epoch = 1
	s, e := startOwnedRole(ctx, c, broker, r, nil, true)
	if e != nil {
		return nil, e
	}
	writer := &lifecycleWriter{session: s, root: c.Root, digest: c.Candidate, fact: writerFact{Attempt: attempt}}
	if _, e = s.receive("startup"); e != nil {
		writer.cleanup()
		return nil, e
	}
	writer.fact.Origin = ownerEpochFact{Command: s.command, Image: s.image, Verified: true, Entered: true}
	b, e := os.ReadFile(fmt.Sprintf("/proc/%d/stat", s.pid.Load()))
	if e != nil {
		return writer, e
	}
	end := strings.LastIndex(string(b), ")")
	if end < 0 {
		return writer, errors.New("writer start identity")
	}
	fields := strings.Fields(string(b[end+1:]))
	if len(fields) < 20 {
		return writer, errors.New("writer start identity")
	}
	writer.fact.Start, e = strconv.ParseUint(fields[19], 10, 64)
	return writer, e
}
func (w *lifecycleWriter) challenge() error {
	var nonce [32]byte
	if _, e := rand.Read(nonce[:]); e != nil {
		return e
	}
	text := hex.EncodeToString(nonce[:])
	s := w.session
	if !s.origin.Live(int(s.pid.Load())) {
		return errors.New("writer not live")
	}
	endChallenge := ownerDiagnosticWait(s.diagnosticContext, "writer challenge send")
	e := s.ch.send("challenge", text, nil)
	endChallenge(e)
	if e != nil {
		return e
	}
	m, e := s.receive("challenge")
	var reply string
	if e != nil || wire.Decode(m.Data, &reply) != nil || reply != qualificationHash([]byte(w.fact.Attempt+text)) || !s.origin.Live(int(s.pid.Load())) {
		return errors.New("writer fresh challenge failed")
	}
	return nil
}
func (w *lifecycleWriter) persist() error {
	if e := w.session.ch.send("persist", nil, nil); e != nil {
		return e
	}
	if _, e := w.session.receive("persist"); e != nil {
		return e
	}
	b, e := os.ReadFile(filepath.Join(w.root, "home", "auth.json"))
	if e != nil || qualificationHash(b) != w.digest {
		return errors.New("writer persist effect missing")
	}
	w.fact.Persisted = true
	return nil
}
func (w *lifecycleWriter) stop(ctx context.Context, binding string) error {
	s := w.session
	endKill := ownerDiagnosticWait(ctx, "writer stop certificate")
	e := s.termination.Kill(ctx, qualificationHash([]byte("writer-stop\x00"+w.fact.Attempt+binding)))
	endKill(e)
	if e != nil {
		return e
	}
	endJoin := ownerDiagnosticWait(ctx, "writer stop join")
	<-s.done
	endJoin(nil)
	w.fact.Stop = s.termination.Facts()
	w.fact.Origin.Joined = s.execution.Joined
	w.fact.Origin.Exit = s.execution.CaseExit
	w.fact.Origin.Waits = s.waits
	if !w.fact.Stop.Valid() || s.err == nil || !s.report.Incomplete || s.waits != 1 {
		return errors.New("writer stop certificate missing")
	}
	return nil
}
func (w *lifecycleWriter) cleanup() {
	s := w.session
	select {
	case <-s.done:
	default:
		s.cancel()
		endJoin := ownerDiagnosticWait(s.diagnosticContext, "writer cleanup join")
		<-s.done
		endJoin(nil)
	}
	s.ch.r.Close()
	s.ch.w.Close()
	s.origin.Close()
	s.cancel()
}

// Count owned launched processes until their supervisor has joined them. A
// refused Start remains a separate attempted-Start violation in the model.
func writerPeak(writers []*lifecycleWriter, peak *int) error {
	live := 0
	for _, w := range writers {
		if w.session.pid.Load() > 0 && !w.session.origin.Facts().Joined {
			live++
		}
	}
	if live > *peak {
		*peak = live
	}
	if live > 1 {
		return errors.New("second physical synthetic writer")
	}
	return nil
}
